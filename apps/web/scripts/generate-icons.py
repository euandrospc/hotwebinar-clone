"""Generate React icons from the checked-in ClickUp SVG subset (Python 3)."""
from pathlib import Path
import hashlib
import json
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1] / 'src/components/icons'
manifest = json.loads((ROOT / 'manifest.json').read_text())

def attr_name(name):
    return re.sub(r'-([a-z])', lambda m: m[1].upper(), name)

def render(element):
    # The selected originals use paths only: fail rather than silently dropping
    # gradients/defs if a future catalog update introduces dependencies.
    assert element.tag.rsplit('}', 1)[-1] == 'path'
    attrs = []
    for key, value in element.attrib.items():
        if key == 'style':
            assert value == 'color:inherit'
            continue
        assert 'url(' not in value and 'var(' not in value
        attrs.append(f'{attr_name(key)}={{{json.dumps(value)}}}')
    return '<path ' + ' '.join(attrs) + ' />'

lines = ['// Generated by scripts/generate-icons.py. Do not edit paths manually.',
         '"use client";', '', 'import { createIcon } from "./create-icon";', '']
components = {}
for name, asset in manifest['icons'].items():
    if asset in components:
        lines.append(f'export const {name} = {components[asset]};')
        continue
    data = (ROOT / 'svg' / f'{asset}.svg').read_bytes()
    assert hashlib.sha256(data).hexdigest() == manifest['sha256'][asset], asset
    svg = ET.fromstring(data)
    components[asset] = name
    children = '\n    '.join(render(child) for child in svg)
    lines.append(f'export const {name} = createIcon({json.dumps(asset)}, {json.dumps(svg.attrib["viewBox"])}, {json.dumps(svg.attrib.get("fill", "currentColor"))}, (\n  <>\n    {children}\n  </>\n));\n')
(ROOT / 'generated.tsx').write_text('\n'.join(lines) + '\n')
print(f'Generated {len(manifest["icons"])} icon exports from {len(components)} verified SVGs.')
